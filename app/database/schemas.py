class AccountHolder(SQLModel, table=True):
    
    __tablename__ = "account_holders"
    __table_args__ = (
            enum_check("relationship", AccountHoldersRelationship, "relationship_valid"),
        )
    
    user_id : uuid.UUID = Field(foreign_key="users.id", primary_key=True, ondelete="CASCADE")
    account_id : uuid.UUID = Field(foreign_key="accounts.id", primary_key=True, ondelete="CASCADE")
    relationship : str = Field(default=AccountHoldersRelationship.PRIMARY,
                               sa_type=String(20),
                               sa_column_kwargs={"server_default": text("'primary'")},
                               nullable=False)
    created_at : datetime = ts_field()
    updated_at : datetime = ts_field(on_update=True)
    
    
class User(SQLModel, table=True):
    
    __tablename__ = "users"
    __table_args__ = (enum_check("status", CustomerStatus, "status_valid"),)
   
    id : uuid.UUID = Field(default_factory=uuid.uuid7, primary_key=True)
    email : str = Field(index=True, unique=True)
    password_hash : str
    phone_number : str = Field(index=True, unique=True)
    first_name : str
    last_name : str
    date_of_birth : date
    address : str
    status : CustomerStatus = Field(nullable=False, 
                         default=CustomerStatus.ACTIVE, 
                         sa_type=String(20),
                         sa_column_kwargs={"server_default": text("'active'")})
    created_at : datetime = ts_field()
    updated_at : datetime = ts_field(on_update=True)
    
    accounts: list["Account"] = Relationship(back_populates="users", link_model=AccountHolder)

class Account(SQLModel, table=True):
    __tablename__ = "accounts"
    __table_args__ = (
        CheckConstraint("balance >= 0", name="balance_non_negative"),
        enum_check("status", AccountStatus, "status_valid"),
        enum_check("account_type", AccountType, "account_type_valid"),
    )
    
    id : uuid.UUID = Field(default_factory=uuid.uuid7, primary_key=True)
    balance : Decimal = money_field(
        default=Decimal("0"), sa_column_kwargs={"server_default": text("0")}
    )
    status : AccountStatus = Field(sa_type=String(20), 
                         nullable=False, 
                         default=AccountStatus.ACTIVE, 
                         sa_column_kwargs={"server_default": text("'active'")})
    account_type : AccountType = Field(sa_type=String(20), 
                               nullable=False, 
                               default=AccountType.CHECKING,
                               sa_column_kwargs={"server_default": text("'checking'")})
    created_at : datetime = ts_field()
    updated_at : datetime = ts_field(on_update=True)
    iban : str = Field(index=True, unique=True)
    
    users: list["User"] = Relationship(back_populates="accounts", link_model=AccountHolder)
    
    
# Foreign keys in the following tables are not set to on delete cascade since we wouldn't want to delete 
# entries from the ledger or transactional record for compliance reasons.
class Transaction(SQLModel, table=True):    
    __tablename__ = "transactions"
    __table_args__ = (
        UniqueConstraint("initiated_by", "idempotency_key", name="uq_txn_idempotency"),
        CheckConstraint("amount > 0", name="amount_positive"),
        enum_check("txn_type", TxnType, "txn_type_valid"),
        enum_check("status", TxnStatus, "status_valid"),
        Index("ix_transactions_initiated_by_created", "initiated_by", "created_at"),
        Index("ix_transactions_status_created", "status", "created_at"),
    )
    
    
    id : uuid.UUID = Field(default_factory=uuid.uuid7, primary_key=True)
    idempotency_key : str = Field(nullable=False)
    initiated_by : uuid.UUID = Field(foreign_key="users.id")
    txn_type : TxnType = Field(sa_type=String(20),
                                       nullable=False,
                                       default=TxnType.TRANSFER,
                                       sa_column_kwargs={"server_default": text("'transfer'")})
    status : TxnStatus = Field(default=TxnStatus.PENDING,
                         sa_type=String(20),
                         sa_column_kwargs={"server_default": text("'pending'")},
                         nullable=False)
    amount : Decimal = money_field()
    currency: str = Field(
        default="USD",
        sa_type=CHAR(3),
        nullable=False,
        sa_column_kwargs={"server_default": text("'USD'")},
    )
    description : Optional[str] = None
    failure_reason : Optional[str] = None
    reverse_transaction_id : Optional[uuid.UUID] = Field(foreign_key="transactions.id")
    created_at : datetime = ts_field()
    updated_at : datetime = ts_field(on_update=True)
    completed_at: Optional[datetime] = Field(
        default=None, sa_type=DateTime(timezone=True)
    )
    
    ledger_entries: list["LedgerEntry"] = Relationship(back_populates="transaction")

    

class LedgerEntry(SQLModel, table=True):
    
    __tablename__ = "ledger_entries"
    __table_args__ = (
        CheckConstraint("amount > 0", name="amount_positive"),
        enum_check("direction", Direction, "direction_valid"),
        Index("ix_ledger_account_created", "account_id", "created_at"),
    )
    
    id : int = identity_pk()
    transaction_id : uuid.UUID = Field(foreign_key="transactions.id")
    account_id : uuid.UUID = Field(foreign_key="accounts.id")
    direction: Direction = Field(sa_type=CHAR(1), nullable=False)
    amount : Decimal = money_field()
    balance_after : Decimal = money_field()
    created_at : datetime = ts_field()

    transaction: Optional[Transaction] = Relationship(back_populates="ledger_entries")

