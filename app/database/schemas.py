def utc_now() -> datetime:
    return datetime.now(timezone.utc)

def enum_check(column: str, enum: type[StrEnum], name:str) -> CheckConstraint:
    """
    Create a SQLAlchemy CheckConstraint for a column based on a StrEnum.
    """
    allowed_values = [e.value for e in enum]
    allowed_values_str = ", ".join(f"'{v}'" for v in allowed_values)
    return CheckConstraint(f"{column} IN ({allowed_values_str})", name=name)

def ts_field(*, on_update: bool = False) -> Any:
    """timestamptz NOT NULL DEFAULT now() (optionally refreshed on UPDATE)."""
    
    """SQLAlchemy, func is a namespace used to call SQL functions. 
    Invoking func.now() creates a SQL expression object that instructs 
    the underlying database to insert its current timestamp 
    (usually rendering as CURRENT_TIMESTAMP or NOW() in the emitted SQL query)."""
    
    """sa_column_args is a SQLModel Field option for passing positional arguments 
    to the SQLAlchemy Column that SQLModel creates for a table field. 
    It’s useful for column-level SQLAlchemy features that SQLModel doesn’t expose 
    as a dedicated Field option. server_default is a SQLAlchemy Column argument 
    that specifies a default value to be generated by the database server 
    when a new row is inserted. onupdate is a SQLAlchemy Column argument 
    that specifies a function to be called when the row is updated, 
    which will be invoked upon update if this column is not present in the 
    SET clause of the update.  """
    
    column_kwargs: dict[str, Any] = {"server_default": func.now()}
    if on_update:
        column_kwargs["onupdate"] = func.now()
    return Field(
        default_factory=utc_now,
        sa_type=DateTime(timezone=True),
        nullable=False,
        sa_column_kwargs=column_kwargs,
    )
 
 
def money_field(**kwargs: Any) -> Any:
    """NUMERIC(18,2) NOT NULL. Never use floats for money."""
    return Field(sa_type=Numeric(18, 2), nullable=False, **kwargs)

 
def identity_pk() -> Any:
    """BIGINT GENERATED ALWAYS AS IDENTITY primary key."""
    return Field(
        default=None,
        sa_column=Column(BigInteger, Identity(always=True), primary_key=True),
    )

